import { useMemo } from 'react';
import type { RepairInfo } from '../api/types';
import { HashChip } from './Copyable';
import { JsonView } from './JsonView';
import { orderKeysByReference, computeDiff, formatDiffValue } from '../lib/repairDisplay';

export function RepairCompare({
  repairInfo,
  before,
  after,
  revalidated,
}: {
  repairInfo: RepairInfo;
  before: Record<string, unknown>;
  after?: Record<string, unknown> | null;
  /** Whether re-validation passed after repair. null = not yet checked. */
  revalidated?: boolean | null;
}) {
  const isSemantic = repairInfo.repair_type === 'semantic';

  // Order repaired output keys to match original for display
  const orderedAfter = useMemo(() => {
    if (!after) return null;
    return orderKeysByReference(before, after);
  }, [before, after]);

  // Compute diff between original and repaired
  const diffs = useMemo(() => {
    if (!after) return [];
    return computeDiff(before, after);
  }, [before, after]);

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
      {/* Badge and provider info */}
      <div className="copy-row">
        <span className={`badge ${isSemantic ? 'badge-accent' : 'badge-pending'}`}>
          {isSemantic ? 'Semantic Repair' : 'Deterministic Repair'}
        </span>
      </div>

      {/* Provider / model metadata for semantic repair */}
      {isSemantic && (
        <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
          {repairInfo.semantic_repair_provider_ref && (
            <span className="badge badge-pending">
              Provider: {repairInfo.semantic_repair_provider_ref}
            </span>
          )}
          {repairInfo.semantic_repair_provider_ref?.includes('Groq') && (
            <span className="badge badge-pending">Model: openai/gpt-oss-20b</span>
          )}
        </div>
      )}

      <p style={{ fontSize: 13.5, color: 'var(--text-muted)' }}>
        {isSemantic
          ? 'The output could not be fixed by rule-based repair, so a candidate fix was generated by the semantic-repair provider. This candidate is never trusted directly — it is re-validated below by the same pipeline that checked the original output.'
          : 'The output was fixed using a bounded, rule-based transformation derived from the schema — no external service or inference was involved.'}
      </p>

      <div className="kv-grid">
        <div className="kv">
          <span className="kv-label">Findings addressed</span>
          <span className="kv-value">{repairInfo.findings_addressed.length}</span>
        </div>
        <div className="kv">
          <span className="kv-label">Pre-repair hash</span>
          <HashChip value={repairInfo.pre_repair_output_hash} />
        </div>
        <div className="kv">
          <span className="kv-label">Post-repair hash</span>
          <HashChip value={repairInfo.post_repair_output_hash} />
        </div>
        {repairInfo.payment_ref && (
          <div className="kv">
            <span className="kv-label">Payment reference</span>
            <HashChip value={repairInfo.payment_ref} />
          </div>
        )}
      </div>

      {/* Original output */}
      <div>
        <div className="section-title">Original output (submitted)</div>
        <JsonView data={before} />
      </div>

      {/* Repaired output — shown ONCE, with original key ordering */}
      {orderedAfter && (
        <div>
          <div className="section-title">Repaired output</div>
          <p style={{ fontSize: 12.5, color: 'var(--text-faint)', marginBottom: 8 }}>
            {isSemantic
              ? 'The candidate repair generated by the semantic-repair provider and accepted by re-validation.'
              : 'The output after deterministic repair was applied and re-validated.'}
          </p>
          <JsonView data={orderedAfter} />
        </div>
      )}

      {/* What Changed */}
      {orderedAfter && diffs.length > 0 && (
        <div>
          <div className="section-title">What changed</div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
            {diffs.map((d) => (
              <div
                key={d.path}
                style={{
                  padding: '10px 14px',
                  background: 'rgba(255,255,255,0.03)',
                  border: '1px solid rgba(255,255,255,0.08)',
                  borderRadius: 8,
                  fontSize: 13,
                }}
              >
                <div style={{ fontWeight: 600, color: 'var(--text)', marginBottom: 4, fontFamily: 'var(--grotesk)' }}>
                  {d.path}
                </div>
                <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
                  <span style={{ color: 'var(--danger)', textDecoration: 'line-through', opacity: 0.7 }}>
                    {formatDiffValue(d.before)}
                  </span>
                  <span style={{ color: 'var(--text-faint)' }}>→</span>
                  <span style={{ color: 'var(--success)', fontWeight: 600 }}>
                    {formatDiffValue(d.after)}
                  </span>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Re-validation status */}
      {revalidated !== undefined && revalidated !== null && (
        <div>
          <div className="section-title">Re-validation</div>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
            <span
              style={{
                color: revalidated ? 'var(--success)' : 'var(--danger)',
                fontWeight: 700,
                fontSize: 15,
              }}
            >
              {revalidated ? '✓' : '✕'}
            </span>
            <span style={{ fontSize: 13.5, color: 'var(--text)' }}>
              {revalidated
                ? 'Passed — the repaired output satisfied the verification pipeline.'
                : 'Failed — the repaired output did not satisfy the verification pipeline.'}
            </span>
          </div>
        </div>
      )}

      {/* Fallback when no repaired output is available */}
      {!orderedAfter && (
        <p style={{ fontSize: 12.5, color: 'var(--text-faint)' }}>
          The repaired output itself isn't echoed back by the API — only its hash is, so the response never re-exposes
          payload content it doesn't have to. The output was re-validated in full before being accepted; its integrity
          is provable by recomputing SHA-256 over it and comparing to <code className="mono">post_repair_output_hash</code>{' '}
          above.
        </p>
      )}
    </div>
  );
}
